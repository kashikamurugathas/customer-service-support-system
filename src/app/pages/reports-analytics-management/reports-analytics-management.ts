import { Component, inject, signal } from '@angular/core';
import { EMPTY, Subscription, catchError, map } from 'rxjs';
import { GraphQLService } from '../../core/graphql/graphql.service';
import { PaginatedGraphQLResult } from '../../core/graphql/graphql.types';
import { GET_REPORTS_QUERY } from '../../core/graphql/management.graphql';
import { DataTable, TableColumn } from '../../shared/components/data-table/data-table';

interface ReportRecord {
  reportId: number | null;
  reportTitle: string | null;
  reportType: string | null;
  reportData: unknown;
  filePath: string | null;
  createdAt: string | null;
  generatedBy: { fullName: string | null } | null;
  ticket: { ticketNumber: string | null } | null;
  agent: { agentId: number | null; userId: { fullName: string | null } | null } | null;
}

interface ReportRow extends Record<string, unknown> {
  reportId: number | null;
  reportTitle: string | null;
  reportType: string | null;
  generatedBy: string | null;
  agentName: string | null;
  ticketNumber: string | null;
  reportData: unknown;
  filePath: string | null;
  createdAt: string | null;
}

interface ReportsResponse {
  allReports?: PaginatedGraphQLResult<ReportRecord> | null;
}

@Component({
  selector: 'app-reports-analytics-management',
  imports: [DataTable],
  styleUrl: './reports-analytics-management.css',
  templateUrl: './reports-analytics-management.html',
})
export class ReportsAnalyticsManagement {
  private readonly graphql = inject(GraphQLService);
  private request?: Subscription;

  readonly columns: TableColumn<ReportRow>[] = [
    { key: 'reportId', label: 'Report ID', type: 'number' },
    { key: 'reportTitle', label: 'Title', truncate: true },
    { key: 'reportType', label: 'Type' },
    { key: 'generatedBy', label: 'Generated By' },
    { key: 'agentName', label: 'Agent' },
    { key: 'ticketNumber', label: 'Ticket' },
    {
      key: 'reportData',
      label: 'Report Data',
      truncate: true,
      formatter: (value) => this.formatReportData(value),
    },
    { key: 'filePath', label: 'File Path', truncate: true },
    { key: 'createdAt', label: 'Created', type: 'date' },
  ];

  readonly reports = signal<ReportRow[]>([]);
  readonly totalRecords = signal(0);
  readonly page = signal(1);
  readonly pageSize = signal(10);
  readonly search = signal('');
  readonly loading = signal(false);
  readonly error = signal<string | null>(null);

  constructor() {
    this.load();
  }

  load(): void {
    this.request?.unsubscribe();
    this.loading.set(true);
    this.error.set(null);

    this.request = this.graphql.query<ReportsResponse>(GET_REPORTS_QUERY, {
      search: this.search() || null,
      reportType: null,
      agentId: null,
      page: this.page(),
      pageSize: this.pageSize(),
    }).pipe(
      map((response) => {
        const result = response.allReports;
        if (!result) throw new Error('The backend returned no report list.');
        return result;
      }),
      catchError((error: unknown) => {
        this.error.set(error instanceof Error ? error.message : String(error));
        this.reports.set([]);
        this.totalRecords.set(0);
        this.loading.set(false);
        return EMPTY;
      })
    ).subscribe((result) => {
      this.reports.set((result.items ?? []).filter((report): report is ReportRecord => report !== null).map((report) => ({
        reportId: report.reportId,
        reportTitle: report.reportTitle,
        reportType: report.reportType,
        generatedBy: report.generatedBy?.fullName ?? null,
        agentName: report.agent?.userId?.fullName ?? null,
        ticketNumber: report.ticket?.ticketNumber ?? null,
        reportData: report.reportData,
        filePath: report.filePath,
        createdAt: report.createdAt,
      })));
      this.totalRecords.set(result.pagination?.totalItems ?? 0);
      this.loading.set(false);
    });
  }

  onSearch(search: string): void {
    this.search.set(search.trim());
    this.page.set(1);
    this.load();
  }

  private formatReportData(value: unknown): string {
    if (value === null || value === undefined) return '—';
    if (typeof value === 'string') return value;
    return JSON.stringify(value) ?? String(value);
  }
}
